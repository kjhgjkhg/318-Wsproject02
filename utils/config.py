"""
utils/config.py - 配置常量模块

定义所有全局常量：
- 目录路径（源目录、输出目录）
- 正则表达式模式
- 限制值（预览长度、TOP数量等）
- 报告文件名模板

路径约束：
- 只读目录：./source_data/
- 只写目录：./output_build/

严禁修改 source_data/ 目录内任何文件！
"""

import os

# =============================================================================
# 目录路径配置
# =============================================================================

# 笔记扫描目录（只读）
SOURCE_DIR = "./source_data"

# 输出目录（只写）
OUTPUT_DIR = "./output_build"

# 配置文件路径（只读，严禁修改）
CONFIG_FILE = os.path.join(SOURCE_DIR, ".do_not_touch.cfg")


# =============================================================================
# 文件处理配置
# =============================================================================

# 支持的文件扩展名
SUPPORTED_EXTENSIONS = {".md", ".markdown"}

# 默认文件编码
DEFAULT_ENCODING = "utf-8"

# 备选编码列表
FALLBACK_ENCODINGS = ["utf-8-sig", "gbk", "gb2312", "latin-1"]


# =============================================================================
# 正则表达式模式
# =============================================================================

# 标签匹配模式：#tag 或 #tag/subtag 或 #tag-name
# 匹配规则：#后跟字母、数字、下划线、连字符、斜杠
TAG_PATTERN = r'#[\w\-/]+'

# 双链匹配模式：[[Page Title]] 或 [[Page Title|Display Text]]
# 捕获组1为链接目标
WIKILINK_PATTERN = r'\[\[([^\]|]+)(?:\|[^\]]*)?\]\]'

# 有效标签格式验证（不含#号）
VALID_TAG_PATTERN = r'^[\w\-/]+$'


# =============================================================================
# 搜索配置
# =============================================================================

# 最大预览行数
MAX_PREVIEW_LINES = 3

# 最大预览字符长度
MAX_PREVIEW_LENGTH = 100

# 上下文行数（匹配行前后）
CONTEXT_LINES = 1

# 搜索结果报告文件名
SEARCH_REPORT_FILENAME = "search_report.txt"


# =============================================================================
# 统计配置
# =============================================================================

# 热门标签显示数量
TOP_TAGS_LIMIT = 10

# 热门双链显示数量
TOP_WIKILINKS_LIMIT = 10

# 统计报告文件名
STATS_REPORT_FILENAME = "stats_report.txt"


# =============================================================================
# 报告格式配置
# =============================================================================

# 分隔线
REPORT_SEPARATOR = "-" * 50

# 报告宽度
REPORT_WIDTH = 70

# 日期时间格式
DATETIME_FORMAT = "%Y-%m-%d %H:%M:%S"


# =============================================================================
# 程序信息
# =============================================================================

# 程序名称
PROGRAM_NAME = "Markdown笔记搜索与统计工具"

# 程序版本
PROGRAM_VERSION = "1.0.0"

# 程序描述
PROGRAM_DESCRIPTION = "本地Markdown笔记快速搜索与标签统计工具（CLI版）"
